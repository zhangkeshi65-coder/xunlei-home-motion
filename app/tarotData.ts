// Rejection sampling gives every card the same probability, with replacement.
export function drawTarotCard(randomUint32: () => number = () => crypto.getRandomValues(new Uint32Array(1))[0]): TarotCard {
  const limit = 0x100000000 - (0x100000000 % TAROT_CARDS.length);
  let value: number;
  do { value = randomUint32(); } while (value >= limit);
  return TAROT_CARDS[value % TAROT_CARDS.length];
}

export function getReading(card: TarotCard, question: string) {
  let context = '把牌中的提醒放回你的日常：现在最想照顾的是什么，又有哪些小事是今天就能开始的？';
  let action = '选择一件今天就能完成的小事';
  if (/考试|学习|作业|考研|读书|成绩|复习/.test(question)) {
    context = '关于学习，把注意力放回可调整的过程：目标、方法与休息是否合适？让这张牌成为复盘的线索，而不把它当作成绩的预告。';
    action = '为下一次学习定一个小目标';
  } else if (/情感|沟通|关系|恋爱|喜欢|朋友|伴侣|对方|分手/.test(question)) {
    context = '关于关系，试着分清自己的感受、需要与对对方的猜测。牌面可以启发一次真诚的对话，答案仍需要彼此沟通与理解。';
    action = '用一句话表达感受和需要';
  } else if (/求职|实习|工作|职业|面试|同事|事业|公司/.test(question)) {
    context = '关于工作，把这张牌当作整理思路的提示：哪些能力、信息或支持是你现在需要的？用现实中的反馈，帮助自己决定下一步。';
    action = '整理一项能力或一个待核实的问题';
  }
  return { meaning: card.meaning, context, advice: [card.practice, EMOTIONS[card.emotion].reminder, action] };
}
